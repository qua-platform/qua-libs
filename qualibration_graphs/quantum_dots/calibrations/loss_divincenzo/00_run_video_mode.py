# %% {Run_video_mode}
@node.run_action(skip_if=node.parameters.simulate)
def run_video_mode(node: QualibrationNode[Parameters, Quam]):
    """Run Video Mode directly from Qualibrate by running this node."""

    # Extract the sensors from the node
    sensors = get_sensors(node)

    # Extract the quam state path from the machine, so that
    quam_state_path = get_quam_state_path(node)

    # Number of repetitions per map
    n_avg = node.parameters.num_shots

    # Find the names of the x-axis, y-axis, and the common virtual gate set.
    x_axis_name, y_axis_name, vgs_id = get_axis_names_and_validate(node)

    # Ensure that the machine is ready to track the integrated voltage
    node.machine.reset_voltage_sequence(vgs_id, track_integrated_voltage=True)

    # Extract a list of the readout pulses that are used. If no sensors are specified in the node parameters,
    # then it uses all of them
    readout_pulses = [s.readout_resonator.operations["readout"] for s in sensors]

    # Whether to include DAC control
    dc_control = node.parameters.dc_control

    # The port to open on localhost
    video_mode_port = node.parameters.video_mode_port

    # Whether to compensate per-line. This cannot be changed in the UI
    per_line_compensation = node.parameters.per_line_compensation

    # The result type to display in the UI, which can be I, Q, Amplitude or Phase
    result_type = node.parameters.result_type

    # Extract the desired span and points
    x_span, x_points = node.parameters.x_span, node.parameters.x_points
    y_span, y_points = node.parameters.y_span, node.parameters.y_points

    # Create an instance of the DataAcquirer and open video mode
    create_video_mode(
        machine=node.machine,
        num_software_averages=n_avg,
        log=node.log,
        x_axis_name=x_axis_name,
        y_axis_name=y_axis_name,
        x_span=x_span,
        x_points=x_points,
        y_span=y_span,
        y_points=y_points,
        virtual_gate_id=vgs_id,
        result_type=result_type,
        dc_control=dc_control,
        readout_pulses=readout_pulses,
        save_path=quam_state_path,
        port=video_mode_port,
        # point_duration = node.parameters.hold_duration,
        mid_scan_compensation=per_line_compensation,
    )


