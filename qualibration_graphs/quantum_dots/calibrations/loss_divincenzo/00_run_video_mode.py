description = """
        RUN VIDEO MODE — INTERACTIVE CHARGE STABILITY SCANNING

Launches an interactive "video mode" dashboard for live-tuning gate voltages while
continuously re-acquiring and displaying a 2D charge-stability map. Unlike the other
nodes in this codebase, this is not a single QUA sweep: it opens a background web
dashboard (via qua_dashboards) that repeatedly drives the OPX to scan the chosen x/y
gate axes and streams I/Q/amplitude/phase back in near real time, so the axes, span,
and readout can be adjusted live from the browser rather than by re-running the node.

Prerequisites:
    - Having initialized the Quam (quam_config/populate_quam_state_*.py).
    - Sensor-dot readout calibrated (resonator calibration nodes completed).
    - The chosen x/y axes belonging to a single, common VirtualGateSet.
    - (Optional) An external DC source configured if ``dc_control=True`` is used to hold
      the scan center on an external DAC.

Datasets:
    - None. This node does not fetch or store a QUA-acquired ``ds_raw``/``ds_fit``; the
      dashboard's live acquisition is self-contained and not persisted via node.results.

Figures:
    - None generated by the node itself. All visualization happens live in the browser
      dashboard at ``http://localhost:<video_mode_port>``.

State update:
    - Voltage points are set interactively via the dashboard's Virtual Gates editor.
"""


node = QualibrationNode[Parameters, Quam](name="00_run_video_mode", description=description, parameters=Parameters())


